// gen-help-files.mjs -- writes js/help_files.js from C's plain-text help
// files in dat/ (the ones display_file() shows: help, hh, history, license,
// opthelp, optmenu, usagehlp, keyhelp, wizhelp), one array of lines per
// file, as dlb_fgets() reads them (newline removed, tabs kept).
//
// usage: node tools/gen-help-files.mjs   (from the repository root)

import { readFileSync, writeFileSync, existsSync } from 'fs';
import { join } from 'path';

const ROOT = new URL('..', import.meta.url).pathname.replace(/\/$/, '');
const base = existsSync(join(ROOT, 'nethack-c/recorder/dat/help'))
    ? 'nethack-c/recorder' : 'nethack-c/upstream';
/* C ref: global.h HELP, SHELP, KEYHELP, DEBUGHELP, HISTORY, LICENSE,
   OPTIONFILE, OPTMENUHELP, USAGEHELP */
const files = ['help', 'hh', 'history', 'license', 'opthelp', 'optmenu',
               'usagehlp', 'keyhelp', 'wizhelp'];

let out = `// help_files.js -- the text of the help files display_file() shows
// (dat/help, hh, history, license, opthelp, optmenu, usagehlp, keyhelp,
// wizhelp): one array of lines per file, newlines removed.
// Generated by tools/gen-help-files.mjs from ${base}/dat; don't edit.
// C ref: global.h HELP &c, wintty.c tty_display_file()

export const help_files = {
`;
for (const f of files) {
    const text = readFileSync(join(ROOT, base, 'dat', f), 'latin1');
    const lines = text.split('\n');
    if (lines[lines.length - 1] === '')
        lines.pop();
    out += `    ${JSON.stringify(f)}: [\n${lines.map(l => `        ${JSON.stringify(l)},\n`).join('')}    ],\n`;
}
out += '};\n';
writeFileSync(join(ROOT, 'js/help_files.js'), out);
console.log(`js/help_files.js: ${files.length} files`);
