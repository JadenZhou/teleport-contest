// gen-data-base.mjs -- writes js/data_base.js from C's dat/data.base, the
// way util/makedefs.c do_data() turns it into the "data" file that
// pager.c checkfile() reads: '#' lines are dropped (d_filter()), a line
// starting with a character > ' ' is an entry name (key), and any other line
// after the first key is a text line of the current entry. Consecutive keys
// share one entry; the text lines are kept as they are (with their leading
// tab), since checkfile() strips the indentation itself.
//
// usage: node tools/gen-data-base.mjs   (from the repository root)

import { readFileSync, writeFileSync, existsSync } from 'fs';
import { join } from 'path';

const ROOT = new URL('..', import.meta.url).pathname.replace(/\/$/, '');
const base = existsSync(join(ROOT, 'nethack-c/recorder/dat/data.base'))
    ? 'nethack-c/recorder' : 'nethack-c/upstream';
const src = readFileSync(join(ROOT, base, 'dat/data.base'), 'latin1');

const entries = [];
let cur = null;
for (const line of src.split('\n').slice(0, -1)) {
    if (line[0] === '#') /* d_filter() */
        continue;
    if (line.length && line.charCodeAt(0) > 0x20) { /* got an entry name */
        if (!cur || cur.text.length) {
            cur = { keys: [], text: [] };
            entries.push(cur);
        }
        cur.keys.push(line);
    } else if (cur) { /* got some descriptive text */
        cur.text.push(line);
    }
}

let out = `// data_base.js -- the entries of dat/data.base, as util/makedefs.c
// do_data() writes them to the "data" file read by pager.c checkfile():
// each entry's names (keys, in file order) and its text lines (with their
// leading indentation, which checkfile() strips).
// Generated by tools/gen-data-base.mjs from ${base}/dat/data.base; don't edit.
// C ref: util/makedefs.c do_data(), src/pager.c checkfile()

export const data_base = [
`;
for (const e of entries)
    out += `    { keys: ${JSON.stringify(e.keys)},\n      text: [\n${e.text.map(t => `        ${JSON.stringify(t)},\n`).join('')}      ] },\n`;
out += '];\n';
writeFileSync(join(ROOT, 'js/data_base.js'), out);
console.log(`js/data_base.js: ${entries.length} entries`);
